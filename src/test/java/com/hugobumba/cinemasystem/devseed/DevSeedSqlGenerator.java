package com.hugobumba.cinemasystem.devseed;

import com.hugobumba.cinemasystem.movie.AgeRating;
import com.hugobumba.cinemasystem.movie.MovieGenre;
import net.datafaker.Faker;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Random;
import java.util.Set;
import java.util.stream.Collectors;
import java.util.stream.IntStream;

public class DevSeedSqlGenerator {

    private static final long FIXED_SEED = 20261120L;
    private static final int CINEMA_COUNT = 5;
    private static final int MOVIE_COUNT = 5;
    private static final int CUSTOMER_COUNT = 10;
    private static final int ROOMS_PER_CINEMA = 4;
    private static final int SEAT_ROWS = 5;
    private static final int SEATS_PER_ROW = 10;
    private static final DateTimeFormatter DATE_TIME_FORMATTER = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    public static void main(String[] args) throws IOException {
        Faker faker = new Faker(new Locale("en"), new Random(FIXED_SEED));
        List<CinemaSeed> cinemas = buildCinemas(faker);
        List<MovieSeed> movies = buildMovies(faker);
        List<UserSeed> users = buildUsers(faker);

        StringBuilder sql = new StringBuilder();
        sql.append("--liquibase formatted sql\n");
        sql.append("--changeset copilot:010-seed-dev context:dev\n\n");
        sql.append("-- Generated by DevSeedSqlGenerator with fixed seed ").append(FIXED_SEED).append("\n\n");

        appendUsers(sql, users);
        appendCinemas(sql, cinemas);
        appendRooms(sql, cinemas);
        appendSeats(sql, cinemas);
        appendMovies(sql, movies);
        appendShowtimes(sql, cinemas, movies);

        Path output = projectRoot().resolve("src/main/resources/db/changelog/changes/010-seed-dev.sql");
        Files.createDirectories(output.getParent());
        Files.writeString(output, sql.toString(), StandardCharsets.UTF_8);
        System.out.println("Generated: " + output.toAbsolutePath());
    }

    private static void appendUsers(StringBuilder sql, List<UserSeed> users) {
        sql.append("-- USERS\n");
        for (UserSeed user : users) {
            sql.append("INSERT INTO users (name, email, password, role)\n")
                    .append("SELECT '").append(escape(user.name())).append("', '").append(escape(user.email())).append("', '")
                    .append(escape(user.password())).append("', '").append(user.role()).append("'\n")
                    .append("WHERE NOT EXISTS (SELECT 1 FROM users WHERE email = '").append(escape(user.email())).append("');\n\n");
        }
    }

    private static void appendCinemas(StringBuilder sql, List<CinemaSeed> cinemas) {
        sql.append("-- CINEMAS\n");
        for (CinemaSeed cinema : cinemas) {
            sql.append("INSERT INTO cinema (name, location)\n")
                    .append("SELECT '").append(escape(cinema.name())).append("', '").append(escape(cinema.location())).append("'\n")
                    .append("WHERE NOT EXISTS (\n")
                    .append("  SELECT 1 FROM cinema WHERE name = '").append(escape(cinema.name())).append("' AND location = '")
                    .append(escape(cinema.location())).append("'\n")
                    .append(");\n\n");
        }
    }

    private static void appendRooms(StringBuilder sql, List<CinemaSeed> cinemas) {
        sql.append("-- ROOMS\n");
        for (CinemaSeed cinema : cinemas) {
            for (int roomNumber = 1; roomNumber <= ROOMS_PER_CINEMA; roomNumber++) {
                sql.append("INSERT INTO room (number, cinema_id)\n")
                        .append("SELECT '").append(roomNumber).append("', c.id FROM cinema c\n")
                        .append("WHERE c.name = '").append(escape(cinema.name())).append("'\n")
                        .append("  AND NOT EXISTS (\n")
                        .append("    SELECT 1 FROM room r WHERE r.cinema_id = c.id AND r.number = '").append(roomNumber).append("'\n")
                        .append("  );\n\n");
            }
        }
    }

    private static void appendSeats(StringBuilder sql, List<CinemaSeed> cinemas) {
        sql.append("-- SEATS\n");
        String seatRowsUnion = IntStream.range(0, SEAT_ROWS)
                .mapToObj(i -> "'" + (char) ('A' + i) + "' AS seat_row")
                .collect(Collectors.joining(" UNION ALL SELECT "));
        String seatNumbersUnion = IntStream.rangeClosed(1, SEATS_PER_ROW)
                .mapToObj(i -> "'" + i + "' AS seat_number")
                .collect(Collectors.joining(" UNION ALL SELECT "));

        for (CinemaSeed cinema : cinemas) {
            for (int roomNumber = 1; roomNumber <= ROOMS_PER_CINEMA; roomNumber++) {
                sql.append("INSERT INTO seat (room_id, seat_row, seat_number)\n")
                        .append("SELECT r.id, seat_rows.seat_row, seat_numbers.seat_number\n")
                        .append("FROM room r\n")
                        .append("JOIN cinema c ON c.id = r.cinema_id\n")
                        .append("CROSS JOIN (SELECT ").append(seatRowsUnion).append(") seat_rows\n")
                        .append("CROSS JOIN (SELECT ").append(seatNumbersUnion).append(") seat_numbers\n")
                        .append("WHERE c.name = '").append(escape(cinema.name())).append("' AND r.number = '").append(roomNumber).append("'\n")
                        .append("  AND NOT EXISTS (\n")
                        .append("    SELECT 1 FROM seat s\n")
                        .append("    WHERE s.room_id = r.id AND s.seat_row = seat_rows.seat_row AND s.seat_number = seat_numbers.seat_number\n")
                        .append("  );\n\n");
            }
        }
    }

    private static void appendMovies(StringBuilder sql, List<MovieSeed> movies) {
        sql.append("-- MOVIES\n");
        for (MovieSeed movie : movies) {
            sql.append("INSERT INTO movie (title, description, poster_url, genre, duration_in_minutes, age_rating)\n")
                    .append("SELECT '").append(escape(movie.title())).append("', '").append(escape(movie.description())).append("', '")
                    .append(escape(movie.posterUrl())).append("', '").append(movie.genre()).append("', ")
                    .append(movie.durationInMinutes()).append(", '").append(movie.ageRating()).append("'\n")
                    .append("WHERE NOT EXISTS (SELECT 1 FROM movie WHERE title = '").append(escape(movie.title())).append("');\n\n");
        }
    }

    private static void appendShowtimes(StringBuilder sql, List<CinemaSeed> cinemas, List<MovieSeed> movies) {
        sql.append("-- SHOWTIMES\n");
        LocalDateTime startDate = LocalDateTime.of(2026, 2, 1, 0, 0);
        int movieIndex = 0;

        for (CinemaSeed cinema : cinemas) {
            for (int roomNumber = 1; roomNumber <= ROOMS_PER_CINEMA; roomNumber++) {
                for (int dayOffset = 0; dayOffset < 3; dayOffset++) {
                    LocalDateTime firstSession = startDate.plusDays(dayOffset).plusHours(12);
                    LocalDateTime secondSession = startDate.plusDays(dayOffset).plusHours(18);
                    appendShowtime(sql, cinema.name(), roomNumber, movies.get(movieIndex++ % movies.size()).title(), firstSession, 8 + roomNumber);
                    appendShowtime(sql, cinema.name(), roomNumber, movies.get(movieIndex++ % movies.size()).title(), secondSession, 8 + roomNumber);
                }
            }
        }
    }

    private static void appendShowtime(StringBuilder sql, String cinemaName, int roomNumber, String movieTitle, LocalDateTime startTime, int price) {
        String timestamp = startTime.format(DATE_TIME_FORMATTER);
        sql.append("INSERT INTO showtime (room_id, movie_id, start_time, price)\n")
                .append("SELECT r.id, m.id, TIMESTAMP '").append(timestamp).append("', ").append(price).append(".00\n")
                .append("FROM room r\n")
                .append("JOIN cinema c ON c.id = r.cinema_id\n")
                .append("JOIN movie m ON m.title = '").append(escape(movieTitle)).append("'\n")
                .append("WHERE c.name = '").append(escape(cinemaName)).append("' AND r.number = '").append(roomNumber).append("'\n")
                .append("  AND NOT EXISTS (\n")
                .append("    SELECT 1 FROM showtime st WHERE st.room_id = r.id AND st.start_time = TIMESTAMP '").append(timestamp).append("'\n")
                .append("  );\n\n");
    }

    private static List<CinemaSeed> buildCinemas(Faker faker) {
        Set<String> uniqueNames = new LinkedHashSet<>();
        List<CinemaSeed> cinemas = new ArrayList<>();
        while (cinemas.size() < CINEMA_COUNT) {
            String name = "Cinema " + faker.company().name().replaceAll("[^A-Za-z0-9 ]", "").trim();
            if (name.length() > 70) {
                name = name.substring(0, 70);
            }
            if (!uniqueNames.add(name)) {
                continue;
            }
            cinemas.add(new CinemaSeed(name, faker.address().cityName()));
        }
        return cinemas;
    }

    private static List<MovieSeed> buildMovies(Faker faker) {
        MovieGenre[] genres = MovieGenre.values();
        AgeRating[] ratings = AgeRating.values();

        List<MovieSeed> movies = new ArrayList<>();
        for (int i = 0; i < MOVIE_COUNT; i++) {
            String title = faker.book().title() + " " + (i + 1);
            String description = faker.lorem().sentence(12);
            String posterUrl = "https://picsum.photos/seed/dev-movie-" + (i + 1) + "/500/750";
            MovieGenre genre = genres[i % genres.length];
            AgeRating ageRating = ratings[i % ratings.length];
            int duration = 90 + (i * 7 % 70);
            movies.add(new MovieSeed(title, description, posterUrl, genre, ageRating, duration));
        }
        return movies;
    }

    private static List<UserSeed> buildUsers(Faker faker) {
        List<UserSeed> users = new ArrayList<>();
        users.add(new UserSeed("Dev Admin", "admin@mail", "123", "ADMIN"));

        for (int i = 0; i < CUSTOMER_COUNT; i++) {
            String name = faker.name().fullName();
            String email = "customer" + (i + 1) + "@mail";
            users.add(new UserSeed(name, email, "123", "CUSTOMER"));
        }
        return users;
    }

    private static String escape(String value) {
        return value.replace("'", "''");
    }

    private static Path projectRoot() {
        return Path.of("").toAbsolutePath();
    }

    private record CinemaSeed(String name, String location) {
    }

    private record MovieSeed(
            String title,
            String description,
            String posterUrl,
            MovieGenre genre,
            AgeRating ageRating,
            int durationInMinutes
    ) {
    }

    private record UserSeed(String name, String email, String password, String role) {
    }
}
